void MX_USART2_UART_Init(void)
{

  /* USER CODE BEGIN USART2_Init 0 */

  /* USER CODE END USART2_Init 0 */

  /* USER CODE BEGIN USART2_Init 1 */

  /* USER CODE END USART2_Init 1 */
  huart2.Instance = USART2;
  huart2.Init.BaudRate = 9600;
  huart2.Init.WordLength = UART_WORDLENGTH_8B;
  huart2.Init.StopBits = UART_STOPBITS_1;
  huart2.Init.Parity = UART_PARITY_NONE;
  huart2.Init.Mode = UART_MODE_TX_RX;
  huart2.Init.HwFlowCtl = UART_HWCONTROL_NONE;
  huart2.Init.OverSampling = UART_OVERSAMPLING_16;
  if (HAL_UART_Init(&huart2) != HAL_OK)
  {
    Error_Handler();
  }
  /* USER CODE BEGIN USART2_Init 2 */

  /* 蓝牙模块（JDY-31）出厂波特率是 9600，而 CubeMX 里 USART2 的默认值是 115200。
   * 这里在 CubeMX 生成的初始化之后**再对齐一次**波特率，值为 app_config.h 的
   * BT_UART_BAUD（9600）。理由：
   *   1) 波特率不一致时收到的是乱码，现象是“一个合法帧都解析不出来”，
   *      很难第一眼定位；这里让代码本身保证 9600，不依赖 .ioc 是否已同步；
   *   2) 这段写在 USER CODE 区内，CubeMX 重新生成代码时会原样保留；
   *   3) 即使以后有人在 CubeMX 里改了波特率，这里也会把它拉回 BT_UART_BAUD
   *      这个“唯一真值来源”，避免 ioc / 代码 / 模块三方各说各话。
   * 注意：改波特率要先把 UE 清零，否则 BRR 要到下一次 UE 上升沿才生效。 */
  if (huart2.Init.BaudRate != BT_UART_BAUD)
  {
    uint32_t pclk1 = HAL_RCC_GetPCLK1Freq();
    __HAL_UART_DISABLE(&huart2);
    huart2.Init.BaudRate = BT_UART_BAUD;
    huart2.Instance->BRR = (uint16_t)((pclk1 + BT_UART_BAUD / 2u) / BT_UART_BAUD);
    __HAL_UART_ENABLE(&huart2);
  }

  /* USER CODE END USART2_Init 2 */

}
